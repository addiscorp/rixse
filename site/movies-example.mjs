// Reproduce the homepage example with the demo's actual WASM engine and helpers.
// No model call. Run: node site/movies-example.mjs [--check]
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import init, { ZegaWasm } from '../demos/canvas/public/zega/zega_wasm.js';
import { moviesBrief, createMoviesWire, createMoviesStore, zegaSource, series, lineData } from '../demos/canvas/lib/movies.ts';
const base = new URL('../demos/canvas/public/zega/', import.meta.url);
await init({ module_or_path: await readFile(new URL('zega_wasm_bg.wasm', base)) });
const source = await readFile(new URL('samples/movies.zql', base), 'utf8');
const db = new ZegaWasm();
const sources = {};
for (const location of JSON.parse(db.load_locations(source, true))) sources[location] = await readFile(new URL(location, base), 'utf8');
db.apply_with_sources(source, JSON.stringify(sources));
zegaSource.run = query => JSON.parse(db.run(source, query));
const schema = source.slice(source.indexOf('schema {'), source.indexOf('display {')).trim() + '\n}';
const brief = moviesBrief(schema);
const top = { id: 'top-10', kind: 'bar', title: 'Top 10 · worldwide box office', query: '{ Movie order by gross desc limit 10 { title gross } }', label: 'title', value: 'gross', limit: 10, size: 'large' };
const store = createMoviesStore();
assert.equal(store.dispatch({ type: 'view.show', payload: top }, 'user').ok, true);
assert.equal(store.dispatch({ type: 'select.set', payload: { view: 'top-10', items: 'Avatar|Titanic' } }, 'user').ok, true);
const state = store.state;
const wire = createMoviesWire();
// Matches Demo.tsx's focus formatter, including its current parenthesized labels.
const names = state.selection.items.map(i => `${i.replace(/^(person|movie|other):/, '')} (${i.split(':')[0]})`);
const focus = `The user has selected: ${names.join(', ')}. "this", "these", "them" and "the selected" mean exactly these, not anything from earlier turns.`;
const request = { brief, message: `compare these over the years\n(${focus})`, history: [], context: wire.encode(state), format: 'wire', legend: wire.legend(), model: 'gemma', vocabulary: createMoviesStore().vocabulary(), rejections: [] };
const action = { id: 'v1', kind: 'line', title: 'Box office by release year', query: '{ Movie(title = "Avatar" || title = "Titanic") limit 100000 { title year gross } }', label: 'title', x: 'year', value: 'gross', size: 'large' };
const rows = zegaSource.run(action.query);
const resolved = wire.resolve({ type: 'view.show', payload: action }, store.params('view.show'));
assert.equal(resolved.payload.id, 'top-10');
assert.equal(store.dispatch(resolved, 'agent').ok, true);
const finalState = store.state;
assert.deepEqual(finalState.order, ['top-10'], 'action replaces the existing chart in place');
const example = { top: series(zegaSource.run(top.query), top), rows, line: lineData(rows, finalState.items['top-10']), request, requestBytes: Buffer.byteLength(JSON.stringify(request)), contextBytes: Buffer.byteLength(request.context), action };
assert.deepEqual(rows.map(r => [r.title, r.year, r.gross]).sort(), [['Avatar', 2009, 2847379794], ['Titanic', 1997, 1850197130]]);
const target = new URL('public/movies-example.json', import.meta.url);
const output = JSON.stringify(example, null, 2) + '\n';
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), output, 'homepage fixture differs from the real demo query');
else await writeFile(target, output);
console.log(`PASS real Zega query: ${JSON.stringify(rows)}; request ${example.requestBytes} bytes; wire ${example.contextBytes} bytes`);
db.free();
